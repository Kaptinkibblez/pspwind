#!/usr/bin/env python3
"""Writes src/mwfuncs.h (MWScript function ids + signatures) from mwsig.py.

    python3 gen_mwfuncs.py            # rewrite the header
    python3 gen_mwfuncs.py --check    # exit 1 if the header is stale
"""

import argparse
import re
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import mwdata  # noqa: E402
import mwsig  # noqa: E402

HEADER = os.path.join(HERE, "..", "..", "src", "mwfuncs.h")


ATTRIBUTES = ["strength", "intelligence", "willpower", "agility", "speed", "endurance",
              "personality", "luck"]
DYNAMICS = ["health", "magicka", "fatigue"]
SKILLS = ["block", "armorer", "mediumarmor", "heavyarmor", "bluntweapon", "longblade", "axe",
          "spear", "athletics", "enchant", "destruction", "alteration", "illusion", "conjuration",
          "mysticism", "restoration", "alchemy", "unarmored", "security", "sneak", "acrobatics",
          "lightarmor", "shortblade", "marksman", "mercantile", "speechcraft", "handtohand"]
EFFECTS = ["resistmagicka", "resistfire", "resistfrost", "resistshock", "resistdisease",
           "resistblight", "resistcorprus", "resistpoison", "resistparalysis", "resistnormalweapons",
           "waterbreathing", "chameleon", "waterwalking", "swimspeed", "superjump", "flying",
           "armorbonus", "castpenalty", "silence", "blindness", "paralysis", "invisible",
           "attackbonus", "defendbonus"]
AI = ["hello", "fight", "flee", "alarm"]

# property ids of the per-reference stat store (vm.c)
PROPS = ([("ATTR_" + a.upper(), None) for a in ATTRIBUTES] + [("DYN_" + d.upper(), None) for d in DYNAMICS]
         + [("DYNBASE_" + d.upper(), None) for d in DYNAMICS] + [("SKILL_" + k.upper(), None) for k in SKILLS]
         + [("EFFECT_" + e.upper(), None) for e in EFFECTS] + [("AI_" + a.upper(), None) for a in AI]
         + [(n, None) for n in ("DISPOSITION", "REPUTATION", "LEVEL", "CRIME", "RANK", "DEATHS",
                               "DISABLED", "SEEDED", "TALKED", "ATTACKED")])
# appended in Milestone 5 (ids above stay stable)
PROPS += ([("ATTRDMG_" + a.upper(), None) for a in ATTRIBUTES]
          + [("SKILLDMG_" + k.upper(), None) for k in SKILLS]
          + [("SKILLPROG_" + k.upper(), None) for k in SKILLS]
          + [("LVLATTR_" + a.upper(), None) for a in ATTRIBUTES]
          + [(n, None) for n in ("LEVELPROG", "DEAD", "LOCK", "GOLDPOOL", "HOSTILE", "DISPTEMP",
                                "CHARM_TARGET", "RESTOCK_DAY", "KILLS", "BOOKREAD",
                                # M7: where an actor was left (zone change persistence)
                                "PLACED", "POSX", "POSY", "POSZ", "POSROT")])
PROP_ID = {name: i for i, (name, _) in enumerate(PROPS)}

FAMILIES = ["NONE", "GET", "SET", "MOD", "SETDYN", "MODDYN", "RATIO", "GET_PC", "SET_PC", "MOD_PC"]
FAM_ID = {f: i for i, f in enumerate(FAMILIES)}


def families():
    """function name -> (family, property) for the stat getter/setter verbs."""
    out = {}
    for a in ATTRIBUTES:
        p = PROP_ID["ATTR_" + a.upper()]
        out["get" + a], out["set" + a], out["mod" + a] = ("GET", p), ("SET", p), ("MOD", p)
    for d in DYNAMICS:
        p = PROP_ID["DYN_" + d.upper()]
        out["get" + d] = ("GET", p)
        out["set" + d] = ("SETDYN", p)
        out["mod" + d] = ("MODDYN", p)
        out["modcurrent" + d] = ("MOD", p)
        out["get" + d + "getratio"] = ("RATIO", p)
    for k in SKILLS:
        p = PROP_ID["SKILL_" + k.upper()]
        out["get" + k], out["set" + k], out["mod" + k] = ("GET", p), ("SET", p), ("MOD", p)
    for e in EFFECTS:
        p = PROP_ID["EFFECT_" + e.upper()]
        out["get" + e], out["set" + e], out["mod" + e] = ("GET", p), ("SET", p), ("MOD", p)
    for a in AI:
        p = PROP_ID["AI_" + a.upper()]
        out["get" + a], out["set" + a], out["mod" + a] = ("GET", p), ("SET", p), ("MOD", p)
    for name, prop in (("disposition", "DISPOSITION"), ("reputation", "REPUTATION")):
        p = PROP_ID[prop]
        out["get" + name], out["set" + name], out["mod" + name] = ("GET", p), ("SET", p), ("MOD", p)
    out["getlevel"], out["setlevel"] = ("GET", PROP_ID["LEVEL"]), ("SET", PROP_ID["LEVEL"])
    p = PROP_ID["CRIME"]
    out["getpccrimelevel"], out["setpccrimelevel"], out["modpccrimelevel"] = \
        ("GET_PC", p), ("SET_PC", p), ("MOD_PC", p)
    return {k: v for k, v in out.items() if k in mwsig.SIGS}


def render() -> str:
    lines = [
        "/* mwfuncs.h - GENERATED by tools/demake_cooker/gen_mwfuncs.py from mwsig.py.",
        " * MWScript instruction/function ids as used by MWBC_CALL / MWBC_CALLX. */",
        "#ifndef PSPWIND_MWFUNCS_H",
        "#define PSPWIND_MWFUNCS_H",
        "",
        "#include <stdint.h>",
        "",
        "enum {",
    ]
    for s in mwsig.BY_ID:
        lines.append(f"    MWF_{s.name.upper()} = {s.id},")
    lines += [f"    MWF_COUNT = {len(mwsig.BY_ID)}", "};", "", "/* per-reference stat store properties */", "enum {"]
    for name, _ in PROPS:
        lines.append(f"    MWP_{name} = {PROP_ID[name]},")
    lines += [f"    MWP_COUNT = {len(PROPS)}", "};", "", "/* stat verb families (mw_func_fam) */", "enum {"]
    for f in FAMILIES:
        lines.append(f"    MWFAM_{f} = {FAM_ID[f]},")
    lines += ["};", "",
              "typedef struct {",
              "    const char *name;",
              "    char kind;          /* 'i' instruction, 'f' function */",
              "    char ret;           /* 'f', 'l' or 0 */",
              "    uint8_t explicit_ok;",
              "    const char *args;   /* signature letters, see mwsig.py */",
              "} MwFuncInfo;", "",
              "#ifdef MWFUNCS_IMPLEMENTATION",
              "const MwFuncInfo mw_funcs[MWF_COUNT] = {"]
    for s in mwsig.BY_ID:
        ret = f"'{s.ret}'" if s.ret else "0"
        lines.append(f'    {{"{s.name}", \'{s.kind}\', {ret}, {int(s.explicit)}, "{s.args}"}},')
    fam = families()
    lines += ["};", "", "const uint8_t mw_func_fam[MWF_COUNT] = {"]
    for i in range(0, len(mwsig.BY_ID), 16):
        chunk = mwsig.BY_ID[i:i + 16]
        lines.append("    " + ", ".join(str(FAM_ID[fam[x.name][0]] if x.name in fam else 0) for x in chunk) + ",")
    lines += ["};", "", "const uint8_t mw_func_prop[MWF_COUNT] = {"]
    for i in range(0, len(mwsig.BY_ID), 16):
        chunk = mwsig.BY_ID[i:i + 16]
        lines.append("    " + ", ".join(str(fam[x.name][1] if x.name in fam else 0) for x in chunk) + ",")
    lines += ["};", "#else", "extern const MwFuncInfo mw_funcs[MWF_COUNT];",
              "extern const uint8_t mw_func_fam[MWF_COUNT];",
              "extern const uint8_t mw_func_prop[MWF_COUNT];", "#endif", "",
              "", "/* magic effect indices (MGEF INDX) */", "enum {"]
    for i, (ident, _g, _f) in enumerate(mwdata.EFFECTS):
        lines.append(f"    MGEF_{re.sub(r'(?<!^)(?=[A-Z])', '_', ident).upper()} = {i},")
    lines += [f"    MGEF_COUNT = {len(mwdata.EFFECTS)}", "};", "",
              "/* skill indices */", "enum {"]
    for i, k in enumerate(SKILLS):
        lines.append(f"    SKILL_{k.upper()} = {i},")
    lines += ["    SKILL_COUNT = 27", "};", "", "enum {"]
    for i, a in enumerate(ATTRIBUTES):
        lines.append(f"    ATTR_{a.upper()} = {i},")
    lines += ["    ATTR_COUNT = 8", "};", "",
              "#endif /* PSPWIND_MWFUNCS_H */", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        try:
            with open(HEADER, encoding="utf-8") as f:
                return 0 if f.read() == text else 1
        except OSError:
            return 1
    with open(HEADER, "w", encoding="utf-8") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
