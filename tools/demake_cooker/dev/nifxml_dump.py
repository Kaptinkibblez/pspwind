#!/usr/bin/env python3
"""Dump niftools nif.xml block layouts evaluated for NIF 4.0.0.2 (Morrowind).

Used to verify tools/demake_cooker/nif.py field by field and to generate
docs/NIF_LAYOUTS.md:

    curl -sSLO https://raw.githubusercontent.com/niftools/nifxml/develop/nif.xml
    python3 dev/nifxml_dump.py nif.xml --markdown > ../../docs/NIF_LAYOUTS.md

With no type names every block type supported by nif.py is dumped.
"""

import argparse
import os
import re
import sys
import xml.etree.ElementTree as ET

VERSION = 0x04000002


def ver(s):
    p = [int(x) for x in s.split(".")] + [0] * 4
    return (p[0] << 24) | (p[1] << 16) | (p[2] << 8) | p[3]


class Spec:
    def __init__(self, path):
        self.root = ET.parse(path).getroot()
        self.tokens = {}
        for tok in self.root.findall("token"):
            for e in tok:
                self.tokens[e.get("token")] = e.get("string")
        self.objs = {e.get("name"): e for e in self.root
                     if e.tag in ("niobject", "struct", "compound")}

    def eval_vercond(self, expr):
        for _ in range(5):
            for k, v in self.tokens.items():
                if k in expr and k not in ("#VER#", "#BSVER#", "#USER#"):
                    expr = expr.replace(k, v)
        expr = expr.replace("#VER#", str(VERSION)).replace("#BSVER#", "0").replace("#USER#", "0")
        expr = re.sub(r"\b(\d+\.\d+\.\d+\.\d+)\b", lambda m: str(ver(m.group(1))), expr)
        for a, b in (("#GTE#", ">="), ("#LTE#", "<="), ("#GT#", ">"), ("#LT#", "<"),
                     ("#EQ#", "=="), ("#NEQ#", "!="), ("#AND#", " and "), ("#OR#", " or "),
                     ("#NOT#", " not ")):
            expr = expr.replace(a, b)
        try:
            return bool(eval(expr, {"__builtins__": {}}, {}))
        except Exception:
            return None  # depends on runtime data; keep the field

    def own_fields(self, name):
        e = self.objs[name]
        out = []
        for f in e.findall("field"):
            since, until = f.get("since"), f.get("until")
            if since and VERSION < ver(since):
                continue
            if until and VERSION > ver(until):
                continue
            if f.get("onlyT") and f.get("onlyT") != name:
                continue
            vc = f.get("vercond")
            if vc and self.eval_vercond(vc) is False:
                continue
            out.append({"name": f.get("name"), "type": f.get("type"),
                        "template": f.get("template") or "",
                        "length": f.get("length") or f.get("arr1") or "",
                        "cond": f.get("cond") or ""})
        return out

    def chain(self, name):
        names = []
        while name:
            names.append(name)
            name = self.objs[name].get("inherit")
        return list(reversed(names))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("nifxml")
    ap.add_argument("types", nargs="*")
    ap.add_argument("--markdown", action="store_true")
    args = ap.parse_args()
    spec = Spec(args.nifxml)
    types = args.types
    if not types:
        sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
        import nif
        types = sorted(nif.READERS)
    if args.markdown:
        print("# NetImmerse 4.0.0.2 block layouts\n")
        print("Generated by `tools/demake_cooker/dev/nifxml_dump.py` from niftools nif.xml,")
        print("evaluated for version 4.0.0.2 / user version 0. `bool` is 32-bit in this")
        print("version; enums are `uint`, `*Flags` bitfields are `ushort`; `string` is a")
        print("`uint` length followed by bytes. Fields are listed per declaring class in")
        print("inheritance order.\n")
    for t in types:
        if t not in spec.objs:
            print(f"{t}: not in nif.xml" if not args.markdown else f"## {t}\n\nNot in nif.xml.\n")
            continue
        chain = spec.chain(t)
        if args.markdown:
            print(f"## {t}\n\nInherits: {' > '.join(chain)}\n")
            print("| Class | Field | Type | Length | Condition |")
            print("|---|---|---|---|---|")
        else:
            print(f"== {t}  ({' > '.join(chain)})")
        for cls in chain:
            for f in spec.own_fields(cls):
                typ = f["type"] + (f"<{f['template']}>" if f["template"] else "")
                if args.markdown:
                    print(f"| {cls} | {f['name']} | {typ} | {f['length']} | {f['cond']} |")
                else:
                    print(f"   {cls:24} {f['name']:28} {typ:28} {f['length']:16} {f['cond']}")
        if args.markdown:
            print()


if __name__ == "__main__":
    main()
